import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDir, '..');

const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const sourcePath = path.join(root, 'src', 'combi-boiler-visual-card.js');
const outputPath = path.join(root, 'dist', 'combi-boiler-visual-card.js');

const source = await readFile(sourcePath, 'utf8');

const banner = `/**
 * Combi Boiler Visual Card v${pkg.version}
 * ${pkg.description}
 * ${pkg.homepage}
 *
 * License: ${pkg.license}
 * Generated from src/combi-boiler-visual-card.js - do not edit this file directly.
 */

`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, banner + source, 'utf8');

console.log(`Built dist/${path.basename(outputPath)} (${banner.length + source.length} bytes)`);
